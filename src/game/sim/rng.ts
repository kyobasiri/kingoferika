// ============================================================
// シード付きの乱数（同じ種なら必ず同じ並びになる）
// ------------------------------------------------------------
// Math.random() は計算側で使わない。乱数が必要なときは
// state.rng を種にしてこの関数で取り出し、種を state に戻す。
// （段階1では未使用。CPU戦などで使う予定）
// ============================================================

import type { GameState } from './state.ts';

/** 0 以上 n 未満の整数を1つ取り出す（xorshift32） */
export function nextInt(s: GameState, n: number): number {
  let x = s.rng | 0;
  x ^= x << 13;
  x ^= x >>> 17;
  x ^= x << 5;
  s.rng = x >>> 0;
  return s.rng % n;
}
